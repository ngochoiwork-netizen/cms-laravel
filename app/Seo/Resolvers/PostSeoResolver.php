<?php

namespace App\Seo\Resolvers;

use App\Models\Post;
use App\Seo\Contracts\SeoResolver;

class PostSeoResolver implements SeoResolver
{
    /**
     * Resolver này xử lý Post.
     */
    public function supports(object $model): bool
    {
        return $model instanceof Post;
    }

    /**
     * Chuẩn hóa dữ liệu SEO cho Post.
     */
    public function resolve(
        object $model,
        string $locale
    ): array {
        /** @var Post $model */

        /*
        |--------------------------------------------------------------------------
        | Translation
        |--------------------------------------------------------------------------
        */

        $translation = $model->translations
            ->firstWhere('locale', $locale);

        /*
        |--------------------------------------------------------------------------
        | Translation Status
        |--------------------------------------------------------------------------
        */

        $hasTranslation = $translation !== null;

        /*
        |--------------------------------------------------------------------------
        | Fallback Translation
        |--------------------------------------------------------------------------
        |
        | Chỉ fallback để tránh thiếu dữ liệu hiển thị.
        | SeoService sẽ noindex nếu locale hiện tại không có translation.
        |
        */

        if (!$translation) {
            $translation =
                $model->translations->firstWhere('locale', 'en')
                ?? $model->translations->firstWhere('locale', 'vi');
        }

        /*
        |--------------------------------------------------------------------------
        | Meta Title
        |--------------------------------------------------------------------------
        */

        $title =
            $translation?->meta_title
            ?: $translation?->title;

        /*
        |--------------------------------------------------------------------------
        | Meta Description
        |--------------------------------------------------------------------------
        */

        $description =
            $translation?->meta_description
            ?: $translation?->short_description;

        /*
        |--------------------------------------------------------------------------
        | Open Graph
        |--------------------------------------------------------------------------
        */

        $ogTitle =
            $translation?->og_title
            ?: $title;

        $ogDescription =
            $translation?->og_description
            ?: $description;

        /*
        |--------------------------------------------------------------------------
        | Result
        |--------------------------------------------------------------------------
        */

        return [

            /*
            |--------------------------------------------------------------------------
            | Locale
            |--------------------------------------------------------------------------
            */

            'locale' => $locale,

            'has_translation' => $hasTranslation,

            /*
            |--------------------------------------------------------------------------
            | General SEO
            |--------------------------------------------------------------------------
            */

            'title' => $title,

            'description' => $description,

            'keywords' => $translation?->meta_keywords,

            /*
            |--------------------------------------------------------------------------
            | Model
            |--------------------------------------------------------------------------
            */

            'model' => $model,

            'model_type' => 'post',

            /*
            |--------------------------------------------------------------------------
            | URL
            |--------------------------------------------------------------------------
            */

            'slug' => $model->slug,

            'canonical_url' => $model->canonical_url,

            /*
            |--------------------------------------------------------------------------
            | Robots
            |--------------------------------------------------------------------------
            |
            | Post hiện tại không có robots riêng.
            | Mặc định index, follow.
            |
            */

            'robots' => 'index, follow',

            /*
            |--------------------------------------------------------------------------
            | Open Graph
            |--------------------------------------------------------------------------
            */

            'og_title' => $ogTitle,

            'og_description' => $ogDescription,

            'og_image' => $model->ogImage,

            /*
            |--------------------------------------------------------------------------
            | Schema
            |--------------------------------------------------------------------------
            */

            'schema_type' =>
                $model->schema_type ?: 'BlogPosting',

            'schema_data' =>
                $translation?->schema_data
                ?: $model->schema_data
                ?: [],

            /*
            |--------------------------------------------------------------------------
            | FAQ Schema
            |--------------------------------------------------------------------------
            */

            'faq_schema' =>
                $translation?->faq_schema ?: [],

            /*
            |--------------------------------------------------------------------------
            | AI Search
            |--------------------------------------------------------------------------
            */

            'ai_overview' =>
                $translation?->ai_overview,

            /*
            |--------------------------------------------------------------------------
            | Article Data
            |--------------------------------------------------------------------------
            |
            | SchemaService sẽ dùng các field này để tạo BlogPosting.
            |
            */

            'published_at' => $model->published_at,

            'updated_at' => $model->updated_at,

            /*
            |--------------------------------------------------------------------------
            | Author
            |--------------------------------------------------------------------------
            */

            'author' => $model->author,

            /*
            |--------------------------------------------------------------------------
            | Category
            |--------------------------------------------------------------------------
            */

            'category' => $model->category,

            /*
            |--------------------------------------------------------------------------
            | Images
            |--------------------------------------------------------------------------
            */

            'thumbnail' => $model->thumbnail,

            'banner' => $model->banner,
        ];
    }
}