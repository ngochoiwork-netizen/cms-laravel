<?php

namespace App\Models;

use Illuminate\Database\Eloquent\Model;

class PageTranslation extends Model
{
    /*
    |--------------------------------------------------------------------------
    | Fillable
    |--------------------------------------------------------------------------
    |
    | Các trường thay đổi theo từng ngôn ngữ.
    |
    | Ví dụ:
    |
    | locale = vi
    | locale = en
    |
    */

    protected $fillable = [
        'page_id',

        'locale',

        /*
        |--------------------------------------------------------------------------
        | Content
        |--------------------------------------------------------------------------
        */

        'title',

        'short_description',

        'content',

        /*
        |--------------------------------------------------------------------------
        | SEO
        |--------------------------------------------------------------------------
        */

        'meta_title',

        'meta_description',

        'meta_keywords',

        /*
        |--------------------------------------------------------------------------
        | Open Graph
        |--------------------------------------------------------------------------
        */

        'og_title',

        'og_description',

        /*
        |--------------------------------------------------------------------------
        | AI / FAQ / Schema
        |--------------------------------------------------------------------------
        */

        'ai_overview',

        'faq_schema',

        'schema_data',
    ];

    /*
    |--------------------------------------------------------------------------
    | Casts
    |--------------------------------------------------------------------------
    */

    protected $casts = [
        'faq_schema' => 'array',

        'schema_data' => 'array',
    ];

    /*
    |--------------------------------------------------------------------------
    | Relations
    |--------------------------------------------------------------------------
    */

    /**
     * Trang gốc.
     *
     * page_translations.page_id
     *            ↓
     * pages.id
     */
    public function page()
    {
        return $this->belongsTo(Page::class);
    }

    /*
    |--------------------------------------------------------------------------
    | Helpers
    |--------------------------------------------------------------------------
    */

    /**
     * Kiểm tra bản dịch tiếng Việt.
     */
    public function isVietnamese(): bool
    {
        return $this->locale === 'vi';
    }

    /**
     * Kiểm tra bản dịch tiếng Anh.
     */
    public function isEnglish(): bool
    {
        return $this->locale === 'en';
    }
}