<?php

namespace App\Models;

use Illuminate\Database\Eloquent\Model;

class ProductTranslation extends Model
{
    /*
    |--------------------------------------------------------------------------
    | Fillable
    |--------------------------------------------------------------------------
    */

    protected $fillable = [
        'product_id',

        'locale',

        /*
        |--------------------------------------------------------------------------
        | Content
        |--------------------------------------------------------------------------
        */

        'name',

        'short_description',

        'description',

        'features',

        /*
        |--------------------------------------------------------------------------
        | SEO
        |--------------------------------------------------------------------------
        */

        'meta_title',

        'meta_description',

        'meta_keywords',

        /*
        |--------------------------------------------------------------------------
        | Open Graph
        |--------------------------------------------------------------------------
        */

        'og_title',

        'og_description',

        /*
        |--------------------------------------------------------------------------
        | AI / FAQ / Schema
        |--------------------------------------------------------------------------
        */

        'faq_schema',

        'schema_data',
    ];

    /*
    |--------------------------------------------------------------------------
    | Casts
    |--------------------------------------------------------------------------
    */

    protected $casts = [
        'features' => 'array',

        'faq_schema' => 'array',

        'schema_data' => 'array',
    ];

    /*
    |--------------------------------------------------------------------------
    | Relations
    |--------------------------------------------------------------------------
    */

    public function product()
    {
        return $this->belongsTo(Product::class);
    }

    /*
    |--------------------------------------------------------------------------
    | Helpers
    |--------------------------------------------------------------------------
    */

    public function isVietnamese(): bool
    {
        return $this->locale === 'vi';
    }

    public function isEnglish(): bool
    {
        return $this->locale === 'en';
    }
}